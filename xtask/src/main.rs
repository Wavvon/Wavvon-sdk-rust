//! `cargo xtask generate [docs-path] [--ref <git-ref>]`
//!
//! Regenerates `src/generated/mod.rs` from a Wavvon-docs checkout and records
//! the docs commit in `src/generated/SPEC_COMMIT`.

use std::path::{Path, PathBuf};
use std::process::Command;

use quote::quote;

use progenitor::{GenerationSettings, Generator, InterfaceStyle};

fn git(docs: &Path, args: &[&str]) -> String {
    let out = Command::new("git")
        .arg("-C")
        .arg(docs)
        .args(args)
        .output()
        .expect("run git");
    assert!(out.status.success(), "git {args:?} failed");
    String::from_utf8(out.stdout)
        .expect("utf8")
        .trim()
        .to_string()
}

fn main() {
    let mut args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("generate") {
        args.remove(0);
    }
    let mut git_ref = None;
    if let Some(i) = args.iter().position(|a| a == "--ref") {
        git_ref = Some(args.remove(i + 1));
        args.remove(i);
    }
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..");
    let docs = root.join(args.first().map_or("../../docs", String::as_str));

    let mut commit = git(&docs, &["rev-parse", git_ref.as_deref().unwrap_or("HEAD")]);
    let text = match &git_ref {
        Some(_) => git(&docs, &["show", &format!("{commit}:openapi.yaml")]),
        None => {
            if !git(&docs, &["status", "--porcelain", "--", "openapi.yaml"]).is_empty() {
                commit.push_str("-dirty");
            }
            std::fs::read_to_string(docs.join("openapi.yaml")).expect("read openapi.yaml")
        }
    };

    let mut value: serde_yaml::Value = serde_yaml::from_str(&text).expect("parse yaml");
    let notes = preprocess(&mut value);
    for n in &notes {
        eprintln!("spec fix: {n}");
    }
    let spec: openapiv3::OpenAPI = serde_yaml::from_value(value).expect("openapi 3.0 shape");

    let mut settings = GenerationSettings::default();
    settings
        .with_interface(InterfaceStyle::Builder)
        .with_inner_type(quote!(crate::session::Session))
        .with_pre_hook_async(quote!(crate::session::attach_bearer));
    let mut generator = Generator::new(&settings);
    let tokens = generator.generate_tokens(&spec).expect("progenitor");
    let ast = syn::parse2(tokens).expect("generated code parses");
    let code = prettyplease::unparse(&ast);
    let out = root.join("src/generated");
    std::fs::create_dir_all(&out).unwrap();
    std::fs::write(
        out.join("mod.rs"),
        format!("// Generated by `cargo xtask generate` from Wavvon-docs openapi.yaml @ {commit}.\n// Do not edit by hand: regenerate instead.\n\n{code}"),
    )
    .unwrap();
    std::fs::write(out.join("SPEC_COMMIT"), format!("{commit}\n")).unwrap();
    println!("generated from Wavvon-docs {commit}");
}

use serde_yaml::{Mapping, Value};

/// crates/hub/src/routes/apps/models.rs, `AppMeResponse`.
const APP_REGISTRATION: &str = r#"
type: object
required: [pubkey, name, commands]
properties:
  pubkey: { type: string }
  name: { type: string }
  avatar_url: { type: string }
  description: { type: string }
  webhook_url: { type: string }
  homepage_url: { type: string }
  commands:
    type: array
    items:
      type: object
      required: [name, description]
      properties:
        name: { type: string }
        description: { type: string }
        args: { type: string }
        scope: { type: string }
        privileged: { type: boolean }
        cooldown_seconds: { type: integer }
"#;

/// Minimal fixes for spec constructs the OpenAPI 3.0 schema (and so progenitor)
/// rejects. Every fix is reported; the real fix belongs in Wavvon-docs.
fn preprocess(spec: &mut Value) -> Vec<String> {
    let mut notes = Vec::new();
    let mut missing_description = 0;
    let mut no_responses = 0;
    let mut dropped: Vec<String> = Vec::new();
    if let Some(Value::Mapping(paths)) = spec.get_mut("paths") {
        for (path, item) in paths.iter_mut() {
            let Value::Mapping(item) = item else { continue };
            for (method, op) in item.iter_mut() {
                let Value::Mapping(op) = op else { continue };
                if !matches!(
                    method.as_str(),
                    Some("get" | "put" | "post" | "delete" | "patch" | "head" | "options")
                ) {
                    continue;
                }
                if has_unsupported_body(op) {
                    dropped.push(format!(
                        "{} {}",
                        method.as_str().unwrap_or("?"),
                        path.as_str().unwrap_or("?")
                    ));
                    continue;
                }
                if !op.contains_key("responses") {
                    let mut ok = Mapping::new();
                    ok.insert("2XX".into(), Value::Mapping(Mapping::new()));
                    op.insert("responses".into(), Value::Mapping(ok));
                    no_responses += 1;
                }
                let Some(Value::Mapping(responses)) = op.get_mut("responses") else {
                    continue;
                };
                for (_, resp) in responses.iter_mut() {
                    fix_response(resp, &mut missing_description);
                }
            }
        }
    }
    // Dropped after the walk: removing while iterating would need two passes anyway.
    if let Some(Value::Mapping(paths)) = spec.get_mut("paths") {
        for entry in &dropped {
            let (method, path) = entry.split_once(' ').expect("method path");
            if let Some(Value::Mapping(item)) = paths.get_mut(path) {
                item.remove(method);
            }
        }
    }
    if !dropped.is_empty() {
        notes.push(format!(
            "progenitor handles only JSON bodies; dropped: {}",
            dropped.join(", ")
        ));
    }
    if let Some(Value::Mapping(schemas)) = spec
        .get_mut("components")
        .and_then(|c| c.get_mut("schemas"))
    {
        if !schemas.contains_key("AppRegistration") {
            let def: Value = serde_yaml::from_str(APP_REGISTRATION).expect("snippet parses");
            schemas.insert("AppRegistration".into(), def);
            notes.push(
                "AppRegistration is referenced but never defined; patched in from AppMeResponse"
                    .into(),
            );
        }
    }
    if missing_description > 0 {
        notes.push(format!(
            "{missing_description} responses without a description got an empty one"
        ));
    }
    if no_responses > 0 {
        notes.push(format!("{no_responses} operations without responses got an empty 2XX (the hub answers 200, 201 or 204 and the spec does not say which)"));
    }
    notes
}

fn fix_response(resp: &mut Value, count: &mut usize) {
    if let Value::Mapping(m) = resp {
        if !m.contains_key("$ref") && !m.contains_key("description") {
            let mut fixed = Mapping::new();
            fixed.insert("description".into(), "".into());
            fixed.extend(std::mem::take(m));
            *m = fixed;
            *count += 1;
        }
    }
}

fn has_unsupported_body(op: &Mapping) -> bool {
    let Some(Value::Mapping(content)) = op.get("requestBody").and_then(|b| b.get("content")) else {
        return false;
    };
    content
        .keys()
        .any(|k| k.as_str() != Some("application/json"))
}
